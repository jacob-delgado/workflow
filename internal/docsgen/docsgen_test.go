func TestRunRefusesACallThatNamesNoDirectory(t *testing.T) {
	t.Parallel()

	// Arrange
	var stderr bytes.Buffer

	// Act
	code := docsgen.Run(nil, io.Discard, &stderr)

	// Assert
	if code != 1 || !strings.Contains(stderr.String(), "usage: docsgen <output-directory>") {
		t.Errorf("docsgen with no directory exited %d saying %q, want 1 and its usage", code, stderr.String())
	}
}

// sealed makes dir readable but not writable for the test's end.
func sealed(t *testing.T, dir string) {
	t.Helper()

	restricted(t, dir, 0o500)
}

// restricted gives dir mode for the test's end, skipping as root, which reads
// and writes whatever a mode says, and on Windows, whose directories keep no
// such bits.
func restricted(t *testing.T, dir string, mode os.FileMode) {
	t.Helper()

	if os.Geteuid() == 0 || runtime.GOOS == "windows" {
		t.Skip("a directory's mode does not keep this user from reading or writing it here")
	}

	err := os.Chmod(dir, mode)
	if err != nil {
		t.Fatal(err)
	}

	t.Cleanup(func() { _ = os.Chmod(dir, 0o700) })
}

func TestRunSaysWhyItCouldNotWriteTheReference(t *testing.T) {
	t.Parallel()

	cases := map[string]struct {
		// where makes the directory a run is pointed at, and the way it fails.
		where func(t *testing.T) string
		want  string
	}{
		"a directory under a file": {want: "creating", where: func(t *testing.T) string {
			t.Helper()

			return filepath.Join(writePage(t, t.TempDir(), "file.md", handWritten), "reference")
		}},
		"a page it cannot read": {want: "reading", where: func(t *testing.T) string {
			t.Helper()

			dir := t.TempDir()
			page := writePage(t, dir, "notes.md", handWritten)
			sealed(t, dir)

			err := os.Chmod(page, 0o000)
			if err != nil {
				t.Fatal(err)
			}

			return dir
		}},
		"a stale page it cannot remove": {want: "removing stale page", where: func(t *testing.T) string {
			t.Helper()

			dir := t.TempDir()
			generate(t, dir)
			sealed(t, dir)

			return dir
		}},
		"a directory it cannot write the pages into": {want: "generating", where: func(t *testing.T) string {
			t.Helper()

			dir := t.TempDir()
			sealed(t, dir)

			return dir
		}},
	}

	for name, tt := range cases {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			// Arrange
			dir := tt.where(t)

			var stderr bytes.Buffer

			// Act
			code := docsgen.Run([]string{dir}, io.Discard, &stderr)

			// Assert
			if code != 1 || !strings.Contains(stderr.String(), tt.want) {
				t.Errorf("docsgen into %s exited %d saying %q, want 1 and %q", name, code, stderr.String(), tt.want)
			}
		})
	}
}

func TestRunNamesADirectoryItCannotList(t *testing.T) {
	t.Parallel()

	// Arrange
	// Writable and searchable but not readable: it can be made and written
	// into, but not listed for the pages an earlier run left.
	dir := t.TempDir()
	restricted(t, dir, 0o300)

	var stderr bytes.Buffer

	// Act
	code := docsgen.Run([]string{dir}, io.Discard, &stderr)

	// Assert
	if code != 1 || !strings.Contains(stderr.String(), "reading "+dir+": ") {
		t.Errorf("docsgen into an unlistable directory exited %d saying %q, want 1 and the directory named",
			code, stderr.String())
	}
}
