// handWritten is a page no run of docsgen wrote.
const handWritten = "# Notes\n\nKept by hand.\n"

// generate runs docsgen into dir, failing the test when it does not succeed.
func generate(t *testing.T, dir string) {
	t.Helper()

	var stderr bytes.Buffer

	if code := docsgen.Run([]string{dir}, io.Discard, &stderr); code != 0 {
		t.Fatalf("docsgen %s exited %d: %s", dir, code, stderr.String())
	}
}

// writePage writes contents to the page name in dir.
func writePage(t *testing.T, dir, name, contents string) string {
	t.Helper()

	path := filepath.Join(dir, name)

	err := os.WriteFile(path, []byte(contents), 0o600)
	if err != nil {
		t.Fatalf("writing %s: %v", path, err)
	}

	return path
}

// readPage is what the page name in dir holds.
func readPage(t *testing.T, dir, name string) string {
	t.Helper()

	contents, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		t.Fatalf("reading %s: %v", name, err)
	}

	return string(contents)
}

func TestRunWritesAPageForEveryCommand(t *testing.T) {
	t.Parallel()

	// Arrange
	dir := filepath.Join(t.TempDir(), "reference")

	// Act
	generate(t, dir)

	// Assert
	pages := []string{"workflow.md", "workflow_config.md", "workflow_config_init.md", "workflow_completion.md"}
	for _, name := range pages {
		_, err := os.Stat(filepath.Join(dir, name))
		if err != nil {
			t.Errorf("docsgen wrote no %s: %v", name, err)
		}
	}
}

func TestRunKeepsAHandWrittenPageAndRemovesAStaleGeneratedOne(t *testing.T) {
	t.Parallel()

	// Arrange
	dir := t.TempDir()
	generate(t, dir)

	// A page an earlier run wrote for a command that is gone since.
	stale := writePage(t, dir, "workflow_gone.md", readPage(t, dir, "workflow_config.md"))
	notes := writePage(t, dir, "notes.md", handWritten)

	// Act
	generate(t, dir)

	// Assert
	_, staleErr := os.Stat(stale)
	if !errors.Is(staleErr, fs.ErrNotExist) {
		t.Errorf("the stale generated page is still there (%v), want it removed", staleErr)
	}

	kept, err := os.ReadFile(notes)
	if err != nil || string(kept) != handWritten {
		t.Errorf("the hand-written page holds %q (%v), want it left as it was", kept, err)
	}
}

func TestRunTitlesEachPageByItsCommandAndSortsItByDepth(t *testing.T) {
	t.Parallel()

	// Arrange
	dir := t.TempDir()

	// Act
	generate(t, dir)

	// Assert
	page := readPage(t, dir, "workflow_config_init.md")
	if !strings.HasPrefix(page, "---\ntitle: \"workflow config init\"\nweight: 30\n---\n") ||
		!strings.Contains(page, "Generated by `task docs:gen`") {
		t.Errorf("workflow_config_init.md opens:\n%.200s\nwant its command as the title, weight 30, and the notice", page)
	}
}

