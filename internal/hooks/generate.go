// File is a file a generated configuration needs written.
type File struct {
	// Path is relative to the repository root.
	Path     string
	Contents string
}

// Generated is a lefthook configuration and the scripts it runs.
type Generated struct {
	Config  string
	Scripts []File
}

// configFileName is the configuration Write creates.
const configFileName = "lefthook.yml"

// Permissions for what Write creates: a configuration anyone may read, and
// scripts git's hooks can run.
const (
	configMode os.FileMode = 0o644
	scriptMode os.FileMode = 0o755
	dirMode    os.FileMode = 0o755
)

// minimumNumberWidth pads job numbers so that ten or more still sort in order.
const minimumNumberWidth = 2

// yamlIndent is the indentation lefthook's own examples use.
const yamlIndent = 2

// Structured writes a configuration that runs each hook of plain commands as
// lefthook jobs, and keeps any other hook as a script. Only a hook whose every
// line is a command lefthook can run on its own is converted: one that reads
// its arguments, branches, or sets variables is kept whole rather than guessed
// at.
func Structured(hooks []GitHook) Generated {
	return generate(hooks, generation{
		convertsPlainHooks: true,
		howHooksRun:        "Hooks it could run as jobs are jobs; the rest run from .lefthook as scripts.",
	})
}

// Verbatim writes a configuration that keeps every hook as the script it is.
func Verbatim(hooks []GitHook) Generated {
	return generate(hooks, generation{
		howHooksRun: "Every hook runs from .lefthook as the script it was.",
	})
}

// generatedFrom opens the header of every configuration, whichever mode wrote it.
const generatedFrom = "Generated by workflow from the hooks this repository already had."

// generation is what sets one mode's configuration apart: whether a hook of
// plain commands becomes jobs, and the header line saying which it did.
type generation struct {
	convertsPlainHooks bool
	howHooksRun        string
}

// generate builds the configuration the way mode says to.
func generate(hooks []GitHook, mode generation) Generated {
	hooksByName := mapping()
	document := &yaml.Node{
		Kind: yaml.DocumentNode, HeadComment: generatedFrom + "\n" + mode.howHooksRun, Content: []*yaml.Node{hooksByName},
	}

	var scripts []File

	for _, hook := range hooks {
		commands, verdict := plainCommands(hook.Script)

		if mode.convertsPlainHooks && verdict == asJobs {
			appendPair(hooksByName, hook.Name, commandsHook(commands))

			continue
		}

		name := scalar(hook.Name)
		if mode.convertsPlainHooks {
			name.HeadComment = verdict.why()
		}

		hooksByName.Content = append(hooksByName.Content, name, scriptHook(hook))
		scripts = append(scripts, File{
			Path: path.Join(".lefthook", hook.Name, hook.Name), Contents: hook.Script,
		})
	}

	return Generated{Config: render(document), Scripts: scripts}
}

// commandsHook is a hook of numbered jobs. It is piped, so the first failure
// stops the rest, as set -e did; and numbered, because lefthook runs piped jobs
// in the order of their NAMES rather than as written — checked against lefthook
// 2.1, where "zeta" ran after "alpha".
func commandsHook(commands []string) *yaml.Node {
	jobs := mapping()
	width := len(strconv.Itoa(len(commands)))

	for index, command := range commands {
		job := mapping()
		appendPair(job, "run", scalar(command))
		appendPair(jobs, fmt.Sprintf("%0*d-%s", max(minimumNumberWidth, width), index+1, jobName(command)), job)
	}

	hook := mapping()
	appendPair(hook, "piped", &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!bool", Value: "true"})
	appendPair(hook, "commands", jobs)

	return hook
}

// scriptHook is a hook that runs its script from .lefthook, which lefthook hands
// git's arguments.
func scriptHook(hook GitHook) *yaml.Node {
	script := mapping()
	appendPair(script, "runner", scalar(runner(hook.Script)))

	scripts := mapping()
	appendPair(scripts, hook.Name, script)

	node := mapping()
	appendPair(node, "scripts", scripts)

	return node
}

// runner is what runs a script, read from its shebang: the interpreter's name
// and its arguments, looking through env. With no shebang, git runs it with sh.
func runner(script string) string {
	first, _, _ := strings.Cut(script, "\n")
	if !strings.HasPrefix(first, "#!") {
		return "sh"
	}

	words := strings.Fields(strings.TrimPrefix(first, "#!"))
	if len(words) == 0 {
		return "sh"
	}

	interpreter, args := path.Base(words[0]), words[1:]
	if interpreter == "env" {
		args = withoutEnvOptions(args)
		if len(args) == 0 {
			return "sh"
		}

		interpreter, args = path.Base(args[0]), args[1:]
	}

	return strings.Join(append([]string{interpreter}, args...), " ")
}

// withoutEnvOptions drops the options env eats before the program it runs: its
// flags (with -u's variable name), and VAR=value assignments. What is left
// begins with the interpreter, or is empty when the line named none.
func withoutEnvOptions(args []string) []string {
	for len(args) > 0 {
		switch {
		case args[0] == "-u" && len(args) > 1:
			args = args[2:]
		case strings.HasPrefix(args[0], "-"):
			args = args[1:]
		case strings.Contains(args[0], "="):
			args = args[1:]
		default:
			return args
		}
	}

	return args
}

// nonJobName matches a run of what cannot be in a job name.
var nonJobName = regexp.MustCompile(`[^a-z0-9]+`)

// toolsWithVerbs name a job by their subcommand too: "go vet", not "go".
func toolsWithVerbs() []string {
	return []string{"go", "npm", "npx", "yarn", "pnpm", "make", "task", "cargo", "bundle", "mise", "uv", "poetry"}
}

// jobName names a job for its command.
func jobName(command string) string {
	words := strings.Fields(command)
	name := path.Base(words[0])

	if slices.Contains(toolsWithVerbs(), name) && len(words) > 1 && !strings.HasPrefix(words[1], "-") {
		name += "-" + words[1]
	}

	cleaned := strings.Trim(nonJobName.ReplaceAllString(strings.ToLower(name), "-"), "-")
	if cleaned == "" {
		return "job"
	}

	return cleaned
}

// mapping is an empty YAML mapping.
func mapping() *yaml.Node {
	return &yaml.Node{Kind: yaml.MappingNode}
}

// scalar is a YAML string. The tag is what makes the encoder quote a value that
// would otherwise read as another type: without it, a hook line of just "false"
// was written as run: false, which lefthook read as a bool and ran as "0".
func scalar(value string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: value}
}

// appendPair adds a key and its value to a mapping.
func appendPair(node *yaml.Node, key string, value *yaml.Node) {
	node.Content = append(node.Content, scalar(key), value)
}

// render writes a document with two-space indentation, which is what
// lefthook's own examples use.
func render(document *yaml.Node) string {
	var out bytes.Buffer

	encoder := yaml.NewEncoder(&out)
	encoder.SetIndent(yamlIndent)

	// A mapping of strings cannot fail to encode.
	_ = encoder.Encode(document)
	_ = encoder.Close()

	return out.String()
}

// Write creates the configuration and its scripts in a repository. It never
// replaces anything: not a lefthook configuration under any name lefthook
// reads, and not an existing script.
//
// Everything is created through the repository opened as a root, which no path
// can leave: the repository's own tree decides what .lefthook is, and a clone
// can make it a link to anywhere at all.
func Write(dir string, generated Generated) error {
	if HasConfig(os.DirFS(dir)) {
		return fmt.Errorf("%w: this repository already has a lefthook configuration", fs.ErrExist)
	}

	root, err := os.OpenRoot(dir)
	if err != nil {
		return fmt.Errorf("creating %s: %w", filepath.Join(dir, configFileName), err)
	}

	err = repository{root: root, dir: dir}.writeAll(generated)

	return errors.Join(err, root.Close())
}

// repository is where Write creates files: the directory, and the root that
// keeps every file created through it inside.
type repository struct {
	root *os.Root
	dir  string
}

// writeAll creates each script and then the configuration, and on any failure
// removes what it created, directories too, so a write that stops part-way
// leaves no lefthook.yml naming scripts it never wrote — which would otherwise
// block the offer from ever being tried again. The configuration comes last for
// a write stopped where nothing can remove what it made, workflow killed or
// crashing: it leaves scripts no configuration names, which a later write
// refuses by name, rather than a configuration that hides the offer. Nothing is
// synced, so a machine that loses power mid-write keeps no such order.
func (r repository) writeAll(generated Generated) error {
	var written []string

	for _, script := range generated.Scripts {
		made, err := r.createScript(script)
		written = append(written, made...)

		if err != nil {
			r.remove(written)

			return err
		}
	}

	err := r.create(configFileName, generated.Config, configMode)
	if err != nil {
		r.remove(written)

		return err
	}

	return nil
}

// createScript creates a script and each directory above it the repository
// lacks, and reports what it created, outermost first, failing or not.
func (r repository) createScript(script File) ([]string, error) {
	name := filepath.FromSlash(script.Path)

	made, err := r.makeDirs(filepath.Dir(name))
	if err != nil {
		return made, err
	}

	err = r.create(name, script.Contents, scriptMode)
	if err != nil {
		return made, err
	}

	return append(made, name), nil
}

// remove removes what a write created, innermost first, so each directory is
// empty by the time its turn comes.
func (r repository) remove(created []string) {
	for _, name := range slices.Backward(created) {
		_ = r.root.Remove(name)
	}
}

// makeDirs creates dir and each parent it lacks, as MkdirAll would, and reports
// the ones it created, outermost first, so a write that fails can remove them
// again.
func (r repository) makeDirs(dir string) ([]string, error) {
	var made []string

	current := ""

	for part := range strings.SplitSeq(dir, string(filepath.Separator)) {
		current = filepath.Join(current, part)

		err := r.root.Mkdir(current, dirMode)
		if errors.Is(err, fs.ErrExist) {
			continue
		}

		if err != nil {
			return made, fmt.Errorf("creating %s: %w", current, err)
		}

		made = append(made, current)
	}

	return made, nil
}

// create writes a new file, refusing one that already exists, and removes the
// file again when it cannot be written whole.
func (r repository) create(name, contents string, mode os.FileMode) error {
	target := filepath.Join(r.dir, name)

	file, err := r.root.OpenFile(name, os.O_WRONLY|os.O_CREATE|os.O_EXCL, mode)
	if err != nil {
		return fmt.Errorf("creating %s: %w", target, err)
	}

	_, writeErr := file.WriteString(contents)

	err = errors.Join(writeErr, file.Close())
	if err != nil {
		return fmt.Errorf("writing %s: %w", target, errors.Join(err, r.root.Remove(name)))
	}

	return nil
}
