#!/usr/bin/env bash
#
# Regenerate the docs' images: a screenshot of each web screen the docs show,
# the filmed web walkthrough and the recorded terminal, written into
# docs/assets/images and each held to a size budget.
#
# Usage:
#   scripts/docs-media.sh
#
# `task docs:media` runs this, by hand: no gate and no CI job does. It builds
# cmd/demo into tmp/demo, has web's `yarn media` screenshot the --web page
# the demo serves and film the loop on it into tmp/walkthrough
# (web/playwright.docs.config.ts), encodes the film into
# web-walkthrough.webp with ffmpeg's libwebp_anim, and has VHS play
# docs/media/terminal.tape over the demo into terminal.gif. VHS types the
# tape into ttyd's web terminal, in bash, films it in a headless Chromium and
# encodes it with ffmpeg, so all four must be there, and ffmpeg's ffprobe.
# Each PNG may be at most 300 KiB, the GIF and the WebP at most 2 MiB each,
# and every image in docs/assets/images must have been written by this run,
# so a screen the docs no longer show cannot linger.
#
# It refuses to film on a busy machine, a load past all but one processor or
# a gate or Playwright run going, since a late frame is a jump in either
# recording (lib/walkthrough.sh). The WebP must be the film its manifest
# describes: animated, 1280 by 800, looping forever, as long as the film
# within a second, with no frame past 250 ms where the film moves throughout,
# a glide, typing or a scroll, every frame it holds the film's own as
# Chromium decodes it (web's media:check), and a keyframe kept for each step
# to look at. The film is PNG and the WebP lossless: a lossy one left blocks
# of earlier frames on screen. ffprobe 6.1 cannot read an animated WebP, so
# lib/webp.sh reads its chunks.
#
# It refuses to run while what the images show, under cmd/, internal/, web/
# or docs/media/ or in go.mod and go.sum, has a change git has not committed,
# so the images committed are of the code committed with them. And the GIF
# must run as long as the tape takes while shown, its sleeps and its typing,
# within a second: VHS films in real time, and on a busy machine it misses
# frames, so the GIF skips past a step the tape holds. A tape that waits on
# the screen while shown has no length to hold the GIF to, and is refused.
#
# Trade-off TRADE-56: the images are regenerated by hand and compared with
# nothing, since their bytes depend on the machine's fonts, Chromium and
# ffmpeg; this checks their sizes, and the reviewer of the commit looks at
# them.
#
# VHS and ttyd are the versions mise.toml pins. A VHS already on PATH at its
# pin, as mise installs it once its release's checksums match, is used;
# otherwise, as in a Claude Code cloud session, where mise cannot install
# either, it is built by `go install`, which sum.golang.org verifies. Every
# ttyd is hashed against the SHA-256 docs/media/tool-checksums.txt pins for
# it before anything runs it, since mise knows no checksum for ttyd and
# installs it unchecked: one on PATH, or behind a mise shim, that matches is
# used, one that does not stops the run, and with none it is downloaded from
# its release and must match. Both go into tmp/docs-media/bin and are used
# again by the next run, and a ttyd kept there that no longer matches is
# downloaded again. ttyd publishes Linux builds alone. check-media-checksums.sh
# (`task lint`) holds the checksums to mise.toml's pin of ttyd and to the
# machines provide_ttyd matches below.
#
# VHS reads no browser setting: it takes the first Chromium go-rod finds on
# PATH and, finding none, downloads one, unpinned, into ~/.cache/rod. So this
# links the Chromium PLAYWRIGHT_CHROMIUM_EXECUTABLE names, or else the
# chromium on PATH, as `chrome` and `chromium`, the names go-rod tries first,
# into a directory put first on PATH; it refuses to run with neither, and
# fails when anything lands in ~/.cache/rod while VHS runs. Run as root,
# Chromium starts only without its sandbox, which VHS_NO_SANDBOX asks for.
#
# The environment is the seam: DOCS_MEDIA_ROOT (the repository this script is
# in) is the checkout it works in.
#
# Exits 0 once every image is written within its budget, the GIF as long as
# its tape and the WebP the film; 1 when a step fails, a ttyd does not match
# its pin, VHS fetched a browser, an image is past its budget or was not
# written, the GIF runs more than a second longer or shorter than its tape, a
# line of the tape has no length to read, or the WebP is not the film; and 2
# when it is given an argument, a tool it needs is missing, ffmpeg cannot
# write an animated WebP, mise.toml pins no VHS or ttyd, ttyd publishes no
# build for the machine, the checkout is not git's or has changes not
# committed to what the images show, the tape waits on the screen while
# shown, or the machine is busy.
set -euo pipefail

if (($# != 0)); then
  sed -n '7,8p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//' >&2
  exit 2
fi

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly here
root="${DOCS_MEDIA_ROOT:-$(cd "${here}/.." && pwd)}"
readonly root
readonly images="${root}/docs/assets/images"
readonly tape="docs/media/terminal.tape"
readonly checksums="${root}/docs/media/tool-checksums.txt"
readonly tools="${root}/tmp/docs-media"
readonly png_budget=$((300 * 1024)) gif_budget=$((2 * 1024 * 1024)) webp_budget=$((2 * 1024 * 1024))

# shellcheck source=lib/dependency-pins.sh
source "${here}/lib/dependency-pins.sh"
# shellcheck source=lib/webp.sh
source "${here}/lib/webp.sh"
# shellcheck source=lib/walkthrough.sh
source "${here}/lib/walkthrough.sh"

# refuse names what is missing and stops the run with status 2.
refuse() {
  echo "docs-media: $*" >&2
  exit 2
}

# fail names the step that failed and stops the run with status 1.
fail() {
  echo "docs-media: $*" >&2
  exit 1
}

# pin prints the version mise.toml pins for a tool, or refuses to run.
#   pin <tool>
pin() {
  local version
  version="$(mise_pins <"${root}/mise.toml" | awk -v tool="$1" '$1 == tool { print $2; exit }')"
  [[ -n "${version}" ]] || refuse "mise.toml pins no version of $1"
  printf '%s' "${version}"
}

# reported prints what the tool PATH finds first says of its version, or
# nothing when PATH has none.
#   reported <tool>
reported() {
  if command -v "$1" >/dev/null; then
    "$1" --version 2>/dev/null || true
  fi
}

# version_pattern prints a regular expression matching a version as a tool
# reports it, "vhs version v0.12.1 (…)" or "ttyd version 1.7.7-40e79c7",
# and no longer version that begins with it.
#   version_pattern <version>
version_pattern() {
  printf '%s' "[[:space:]]v?${1//./[.]}([-[:space:]]|$)"
}

# link_chromium puts the Chromium to film with first on PATH under the names
# go-rod looks for first, or refuses to run without one.
link_chromium() {
  local browser="${PLAYWRIGHT_CHROMIUM_EXECUTABLE:-}"
  if [[ -z "${browser}" ]]; then
    browser="$(command -v chromium || true)"
  fi
  if [[ -z "${browser}" || ! -x "${browser}" ]]; then
    refuse "no Chromium: set PLAYWRIGHT_CHROMIUM_EXECUTABLE or put chromium on PATH, or VHS downloads one of its own"
  fi
  # A link holds its target as written, read from the link's own directory,
  # so a relative path would point at nothing there.
  browser="$(cd -- "$(dirname -- "${browser}")" && pwd)/$(basename -- "${browser}")"
  mkdir -p "${tools}/browser"
  ln -sfn "${browser}" "${tools}/browser/chrome"
  ln -sfn "${browser}" "${tools}/browser/chromium"
  [[ -x "${tools}/browser/chrome" ]] || refuse "the Chromium link ${tools}/browser/chrome does not resolve"
  PATH="${tools}/browser:${PATH}"
}

# provide_vhs leaves VHS at its pin on PATH, building it when it is not.
provide_vhs() {
  local version wanted found cache="${tools}/go-build"
  version="$(pin vhs)"
  wanted="$(version_pattern "${version}")"
  found="$(reported vhs)"
  if [[ "${found}" =~ ${wanted} ]]; then
    return
  fi
  echo "docs-media: building VHS v${version} into ${tools}/bin"
  # A build cache of its own, removed after, so a tool built once leaves
  # nothing in the developer's.
  if ! GOBIN="${tools}/bin" GOCACHE="${cache}" go install "github.com/charmbracelet/vhs@v${version}"; then
    rm -rf "${cache}"
    fail "could not build VHS v${version}"
  fi
  rm -rf "${cache}"
  found="$(reported vhs)"
  if [[ ! "${found}" =~ ${wanted} ]]; then
    fail "the VHS on PATH is not v${version}"
  fi
}

# ttyd_file prints the file the ttyd on PATH runs, the one behind a mise shim
# rather than mise, or nothing when PATH has none.
ttyd_file() {
  local found
  found="$(command -v ttyd || true)"
  [[ -n "${found}" ]] || return 0
  found="$(readlink -f "${found}")"
  if [[ "${found##*/}" == mise ]]; then
    found="$("${found}" which ttyd 2>/dev/null || true)"
  fi
  printf '%s' "${found}"
}

# download_ttyd downloads ttyd's release for this machine into tools/bin,
# keeping it only once it matches its pin.
#   download_ttyd <version> <machine>
download_ttyd() {
  local download="${tools}/bin/ttyd.download"
  command -v curl >/dev/null || refuse "no curl to download ttyd with"
  echo "docs-media: downloading ttyd $1 into ${tools}/bin"
  if ! curl -fsSL "https://github.com/tsl0922/ttyd/releases/download/$1/ttyd.$2" -o "${download}"; then
    rm -f "${download}"
    fail "could not download ttyd $1"
  fi
  if ! "${here}/verify-download.sh" "${checksums}" "${download}" ttyd "$1" "$2"; then
    rm -f "${download}"
    exit 1
  fi
  chmod +x "${download}"
  mv "${download}" "${tools}/bin/ttyd"
}

# provide_ttyd leaves on PATH a ttyd whose bytes are the release its pin
# names, hashed before anything runs it: the one PATH has when it matches,
# and otherwise one downloaded, in place of a copy an earlier run kept that
# no longer matches; a ttyd elsewhere on PATH that does not match stops the
# run.
provide_ttyd() {
  local version machine wanted found kept="${tools}/bin/ttyd"
  version="$(pin ttyd)"
  wanted="$(version_pattern "${version}")"
  machine="$(uname -m)"
  if [[ "$(uname -s)" != Linux || ! "${machine}" =~ ^(x86_64|aarch64)$ ]]; then
    refuse "ttyd ${version} publishes no build for $(uname -s) ${machine}"
  fi
  if [[ -e "${kept}" ]] && ! "${here}/verify-download.sh" "${checksums}" "${kept}" ttyd "${version}" "${machine}"; then
    echo "docs-media: ${kept} is not ttyd ${version} as released; downloading it again"
    rm -f "${kept}"
  fi
  found="$(ttyd_file)"
  if [[ -z "${found}" ]]; then
    download_ttyd "${version}" "${machine}"
    found="${kept}"
  elif ! "${here}/verify-download.sh" "${checksums}" "${found}" ttyd "${version}" "${machine}"; then
    fail "the ttyd on PATH, ${found}, is not ttyd ${version} as released: remove it or take it off PATH, and this downloads its own"
  fi
  if [[ ! "$("${found}" --version 2>/dev/null || true)" =~ ${wanted} ]]; then
    fail "the ttyd on PATH is not ${version}"
  fi
}

# record plays the tape over the demo, and fails when VHS fetched a browser
# of its own rather than film with the one linked.
#   record <started>
record() {
  local rod="${HOME}/.cache/rod"
  (
    cd "${root}"
    if [[ "$(id -u)" == 0 ]]; then
      export VHS_NO_SANDBOX=true
    fi
    vhs "${tape}"
  ) || fail "VHS could not record ${tape}"
  if [[ -n "$(find "${rod}" -newer "$1" -print -quit 2>/dev/null || true)" ]]; then
    fail "VHS downloaded a browser into ${rod}: remove it, and put a Chromium on PATH"
  fi
}

# clean_inputs refuses to run while what the images show — the demo, the
# interface, the tape, the web app and the modules they build from — has a
# change not committed, so the images committed show the code committed
# beside them, not a working tree that has since gone.
clean_inputs() {
  local changed
  changed="$(git -C "${root}" status --porcelain --untracked-files=all -- cmd internal web docs/media go.mod go.sum 2>/dev/null)" \
    || refuse "${root} is not a git checkout, so what its images show cannot be known to be committed"
  if [[ -n "${changed}" ]]; then
    refuse "what the images show has changes not committed; commit them first, so the images show what is:
${changed}"
  fi
}

# duration_ms prints a VHS duration — 2.5s, 600ms, or a bare number of
# seconds, as ffprobe prints one — in whole milliseconds, and nothing for
# one it cannot read.
#   duration_ms <duration>
duration_ms() {
  [[ "$1" =~ ^([0-9]+)(\.([0-9]+))?(ms|s)?$ ]] || return 0
  local whole="${BASH_REMATCH[1]}" fraction="${BASH_REMATCH[3]}000" unit="${BASH_REMATCH[4]:-s}"
  if [[ "${unit}" == ms ]]; then
    printf '%d' "$((10#${whole}))"
  else
    printf '%d' "$((10#${whole} * 1000 + 10#${fraction:0:3}))"
  fi
}

# seconds prints milliseconds as seconds to two places.
#   seconds <milliseconds>
seconds() {
  printf '%d.%02d' "$(($1 / 1000))" "$(($1 % 1000 / 10))"
}

# keys_ms prints how long a typing command takes in milliseconds — a Type,
# each character of its text, or a key, once or the count it is given — at
# its own @ speed, or at the typing speed given, and nothing when its speed
# cannot be read.
#   keys_ms <command> <arguments> <typing speed ms>
keys_ms() {
  local speed="$3" count=1 text
  if [[ "$1" == *@* ]]; then
    speed="$(duration_ms "${1#*@}")"
    [[ -n "${speed}" ]] || return 0
  fi
  if [[ "$1" == Type* ]]; then
    text="${2:1}"
    count="${#text}"
    count=$((count - 1))
  elif [[ "$2" =~ ^[0-9]+$ ]]; then
    count="$2"
  fi
  printf '%d' "$((count * speed))"
}

# line_ms prints how long one of the tape's lines takes, in milliseconds, at
# the typing speed given: a Sleep, a Type or a key, and 0 for any other; and
# nothing for one it cannot read.
#   line_ms <line> <typing speed ms>
line_ms() {
  local command arguments
  read -r command arguments <<<"$1" || true
  case "${command}" in
    Sleep) duration_ms "${arguments}" ;;
    Type* | Enter* | Backspace* | Delete* | Insert* | Tab* | Space* | Escape* | Up* | Down* | Left* | Right* | \
      PageUp* | PageDown* | ScrollUp* | ScrollDown* | Ctrl+* | Alt+* | Shift+*)
      keys_ms "${command}" "${arguments}" "$2"
      ;;
    *) printf '0' ;;
  esac
}

# shown_ms prints how long the tape takes while it is shown, which the GIF
# must run, in milliseconds: each Sleep, and each character typed and key
# pressed at its typing speed, VHS's own 50 ms until the tape sets one. A
# line it cannot read stops the run, and a Wait while shown is refused: it
# lasts as long as the screen takes, so how long the GIF runs could not be
# known.
shown_ms() {
  local line command arguments shown=1 speed=50 total=0 took
  while IFS= read -r line || [[ -n "${line}" ]]; do
    read -r command arguments <<<"${line}" || true
    case "${command}" in
      Hide) shown=0 ;;
      Show) shown=1 ;;
      Set)
        if [[ "${arguments}" =~ ^TypingSpeed[[:space:]]+([^[:space:]]+) ]]; then
          speed="$(duration_ms "${BASH_REMATCH[1]}")"
          [[ -n "${speed}" ]] || fail "${tape}: cannot read ${line}"
        fi
        ;;
      '' | \#*) ;;
      *)
        ((shown)) || continue
        [[ "${command}" != Wait* ]] \
          || refuse "${tape} waits on the screen while it is shown, so how long its GIF runs cannot be known: ${line}"
        took="$(line_ms "${line}" "${speed}")"
        [[ -n "${took}" ]] || fail "${tape}: cannot read how long this takes: ${line}"
        total=$((total + took))
        ;;
    esac
  done <"${root}/${tape}"
  printf '%d' "${total}"
}

# check_length stops the run when the GIF does not run as long as its tape
# takes shown, within a second: VHS films in real time, a frame at a time,
# and every frame it cannot take in time, on a machine busy with something
# else, is time the GIF loses, the screen jumping past a step the tape holds;
# even on an idle machine it runs about half a second short.
#   check_length <shown ms>
check_length() {
  local gif="${images}/terminal.gif" probed runs
  probed="$(ffprobe -v error -show_entries format=duration -of default=noprint_wrappers=1:nokey=1 "${gif}")"
  runs="$(duration_ms "${probed}")"
  [[ -n "${runs}" ]] || fail "ffprobe gave ${gif##*/} no length: ${probed}"
  if ((runs - $1 > 1000 || $1 - runs > 1000)); then
    fail "${gif##*/}: runs $(seconds "${runs}") s where its tape's $(seconds "$1") s do; VHS lost or gained time filming it, as on a busy machine: run the task again on an idle one"
  fi
  echo "ok    ${gif##*/}: runs $(seconds "${runs}") s, as its tape's $(seconds "$1") s do"
}

# check_sizes prints each image's size, and stops the run when one is past
# its budget or was not written since the run started.
#   check_sizes <started>
check_sizes() {
  local image bytes budget failed=0
  shopt -s nullglob
  for image in "${images}"/*.png "${images}"/*.gif "${images}"/*.webp; do
    bytes="$(wc -c <"${image}")"
    bytes=$((bytes))
    case "${image}" in
      *.gif) budget="${gif_budget}" ;;
      *.webp) budget="${webp_budget}" ;;
      *) budget="${png_budget}" ;;
    esac
    if [[ -z "$(find "${image}" -newer "$1" -print)" ]]; then
      echo "FAIL  ${image##*/}: not written by this run; delete it if the docs no longer show it" >&2
      failed=1
    elif ((bytes > budget)); then
      echo "FAIL  ${image##*/}: ${bytes} bytes, past its budget of ${budget}" >&2
      failed=1
    else
      echo "ok    ${image##*/}: ${bytes} bytes, within its budget of ${budget}"
    fi
  done
  shopt -u nullglob
  if ((failed)); then
    fail "an image is past its budget or was not written"
  fi
}

