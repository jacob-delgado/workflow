import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { defineConfig } from '@playwright/test'
import { z } from 'zod'
import { desktopChrome } from './playwright.config.ts'

// releasedVersion is the version release-please last released, as a release
// build of workflow reports it in the header: the tag, with its v.
function releasedVersion(): string {
  const manifest = join(import.meta.dirname, '..', '.release-please-manifest.json')
  const released = z.object({ '.': z.string() }).parse(JSON.parse(readFileSync(manifest, 'utf8')))

  return `v${released['.']}`
}

// demo is the demo binary each test serves the page from, built by
// scripts/docs-media.sh; the demo serves the committed bundle, so the images
// show what a release build serves.
const demo = join(import.meta.dirname, '..', 'tmp', 'demo')

// browser is how both projects open the page: one device pixel to a CSS
// pixel, so each image is exactly the window's size, and dates read in
// English and in UTC on any machine.
const browser = {
  ...desktopChrome,
  deviceScaleFactor: 1,
  timezoneId: 'UTC',
  locale: 'en-US',
}

// The docs' media, over the real --web server running the demo's world, a
// demo of its own for each test (e2e/docs/demo.ts): e2e/docs/media.spec.ts
// writes a PNG of each screen the docs show into docs/assets/images, and
// e2e/docs/walkthrough.spec.ts films the loop into tmp/walkthrough for
// scripts/docs-media.sh to encode. Both are regenerated by hand and compared
// by nothing. They run apart from playwright.config.ts, which leaves e2e/docs
// out, so neither `task e2e` nor CI rewrites a committed image. version is
// what the page's header names the build, the released one, as a user's
// does.
export default defineConfig({
  testDir: 'e2e/docs',
  workers: 1,
  forbidOnly: true,
  retries: 0,
  reporter: 'list',
  projects: [
    {
      name: 'docs-media',
      testMatch: 'media.spec.ts',
      // mediaDir is where the spec writes each image: the docs site's assets,
      // which its image shortcode reads.
      metadata: {
        mediaDir: join(import.meta.dirname, '..', 'docs', 'assets', 'images'),
        demo,
        version: releasedVersion(),
      },
      use: browser,
    },
    {
      name: 'docs-walkthrough',
      testMatch: 'walkthrough.spec.ts',
      // walkthroughDir is where the film's frames, keyframes and manifest go,
      // under the repository's gitignored tmp/, for the encoding to read.
      metadata: {
        walkthroughDir: join(import.meta.dirname, '..', 'tmp', 'walkthrough'),
        demo,
        version: releasedVersion(),
      },
      use: { ...browser, viewport: { width: 1280, height: 800 } },
    },
  ],
})
