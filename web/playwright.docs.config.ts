import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { defineConfig } from '@playwright/test'
import { z } from 'zod'
import { desktopChrome } from './playwright.config.ts'

// releasedVersion is the version release-please last released, as a release
// build of workflow reports it in the header: the tag, with its v.
function releasedVersion(): string {
  const manifest = join(import.meta.dirname, '..', '.release-please-manifest.json')
  const released = z.object({ '.': z.string() }).parse(JSON.parse(readFileSync(manifest, 'utf8')))

  return `v${released['.']}`
}

// The docs' screenshots: e2e/docs/media.spec.ts opens the cockpit over the
// real --web server running the demo's world, a demo of its own for each
// screen (e2e/docs/demo.ts), and writes a PNG of each screen the docs show
// into docs/assets/images, regenerated by hand and compared by nothing. It
// runs apart from playwright.config.ts, which leaves e2e/docs out, so neither
// `task e2e` nor CI rewrites a committed image. scripts/docs-media.sh builds
// the demo before it runs this; the demo serves the committed bundle, so the
// images show what a release build serves.
export default defineConfig({
  testDir: 'e2e/docs',
  workers: 1,
  forbidOnly: true,
  retries: 0,
  reporter: 'list',
  projects: [
    {
      name: 'docs-media',
      // mediaDir is where the spec writes each image: the docs site's assets,
      // which its image shortcode reads; demo is the demo binary each test
      // serves the page from; version is what its header names the build,
      // the released one, as a user's does.
      metadata: {
        mediaDir: join(import.meta.dirname, '..', 'docs', 'assets', 'images'),
        demo: join(import.meta.dirname, '..', 'tmp', 'demo'),
        version: releasedVersion(),
      },
      use: {
        ...desktopChrome,
        // One device pixel to a CSS pixel, so each image is exactly the
        // window's size, and dates read in English and in UTC on any machine.
        deviceScaleFactor: 1,
        timezoneId: 'UTC',
        locale: 'en-US',
      },
    },
  ],
})
